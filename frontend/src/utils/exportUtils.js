import { jsPDF } from 'jspdf';

export const copySummaryToClipboard = (summary) => {
  if (!summary) return false;

  const content = `
=====================================================
${summary.title || 'YouTube Summary'}
Channel: ${summary.channel || 'N/A'}
Video URL: ${summary.url}
Duration: ${summary.duration_formatted || 'N/A'}
Generated by: TubeSage AI (${summary.mode} mode, ${summary.language})
=====================================================

--- OVERVIEW ---
${summary.overview || ''}

--- MAIN SUMMARY ---
${summary.main_summary || ''}

--- KEY TAKEAWAYS ---
${(summary.key_takeaways || []).map((t, i) => `${i + 1}. ${t}`).join('\n')}

--- IMPORTANT CONCEPTS ---
${(summary.important_concepts || []).map(c => `• ${c.concept}: ${c.explanation}`).join('\n\n')}

--- IMPORTANT EXAMPLES ---
${(summary.important_examples || []).map((e, i) => `[Example ${i + 1}] ${e}`).join('\n')}

--- ACTIONABLE INSIGHTS ---
${(summary.actionable_insights || []).map((a, i) => `[Action ${i + 1}] ${a}`).join('\n')}

--- KEY TIMESTAMPS ---
${(summary.timestamps || []).map(ts => `[${ts.time}] ${ts.title}: ${ts.summary}`).join('\n')}

--- CONCLUSION ---
${summary.conclusion || ''}

--- KEYWORDS ---
${(summary.keywords || []).join(', ')}
`;

  return navigator.clipboard.writeText(content.trim());
};

export const downloadSummaryAsTxt = (summary) => {
  if (!summary) return;

  const content = `=====================================================
${summary.title || 'YouTube Summary'}
Channel: ${summary.channel || 'N/A'}
Video URL: ${summary.url}
Generated by: TubeSage AI
=====================================================

1. OVERVIEW:
${summary.overview || 'N/A'}

2. MAIN SUMMARY:
${summary.main_summary || 'N/A'}

3. KEY TAKEAWAYS:
${(summary.key_takeaways || []).map((t, i) => `  * ${t}`).join('\n')}

4. IMPORTANT CONCEPTS:
${(summary.important_concepts || []).map(c => `  * ${c.concept}\n    ${c.explanation}`).join('\n\n')}

5. ACTIONABLE INSIGHTS:
${(summary.actionable_insights || []).map((a, i) => `  * ${a}`).join('\n')}

6. KEY TIMESTAMPS:
${(summary.timestamps || []).map(ts => `  [${ts.time}] ${ts.title}\n    ${ts.summary}`).join('\n\n')}

7. CONCLUSION:
${summary.conclusion || 'N/A'}
`;

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  const safeTitle = (summary.title || 'summary').replace(/[^a-z0-9]/gi, '_').toLowerCase().slice(0, 40);
  link.href = url;
  link.download = `TubeSage_${safeTitle}.txt`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

export const downloadSummaryAsPdf = (summary) => {
  if (!summary) return;

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 16;
  const maxWidth = pageWidth - (margin * 2);
  let y = margin;

  // Header banner background
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Title in banner
  doc.setTextColor(168, 85, 247); // purple-500
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('TubeSage AI', margin, 14);

  doc.setTextColor(203, 213, 225); // slate-300
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Smart Multilingual YouTube Summary Report', margin, 21);

  doc.setTextColor(148, 163, 184); // date on top right
  doc.text(new Date().toLocaleDateString(), pageWidth - margin - 22, 14);

  y = 36;

  // Helper function to check page overflow
  const checkPageBreak = (neededHeight) => {
    if (y + neededHeight > pageHeight - margin) {
      doc.addPage();
      y = margin;
      return true;
    }
    return false;
  };

  // Video Title
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  const titleLines = doc.splitTextToSize(summary.title || 'YouTube Summary', maxWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 6 + 3;

  // Meta stats
  doc.setTextColor(100, 116, 139);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  const metaText = `Channel: ${summary.channel || 'N/A'} | Duration: ${summary.duration_formatted || 'N/A'} | Mode: ${summary.mode} | Language: ${summary.language}`;
  doc.text(metaText, margin, y);
  y += 8;

  // Divider line
  doc.setDrawColor(226, 232, 240);
  doc.line(margin, y, pageWidth - margin, y);
  y += 7;

  const addSection = (title, content, isList = false) => {
    if (!content || (Array.isArray(content) && content.length === 0)) return;

    checkPageBreak(14);

    doc.setTextColor(124, 58, 237); // violet
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.text(title.toUpperCase(), margin, y);
    y += 6;

    doc.setTextColor(51, 65, 85);
    doc.setFontSize(9.5);
    doc.setFont('helvetica', 'normal');

    if (isList && Array.isArray(content)) {
      content.forEach((item) => {
        const itemText = typeof item === 'string' ? item : (item.explanation ? `${item.concept}: ${item.explanation}` : JSON.stringify(item));
        const lines = doc.splitTextToSize(`• ${itemText}`, maxWidth - 4);
        checkPageBreak(lines.length * 4.5 + 2);
        doc.text(lines, margin + 2, y);
        y += lines.length * 4.5 + 2;
      });
    } else {
      const lines = doc.splitTextToSize(content, maxWidth);
      checkPageBreak(lines.length * 4.8 + 2);
      doc.text(lines, margin, y);
      y += lines.length * 4.8 + 2;
    }

    y += 4;
  };

  // Sections
  addSection('Overview', summary.overview);
  addSection('Main Summary', summary.main_summary);
  addSection('Key Takeaways', summary.key_takeaways, true);
  addSection('Important Concepts', summary.important_concepts, true);
  if (summary.actionable_insights?.length) {
    addSection('Actionable Insights', summary.actionable_insights, true);
  }
  if (summary.timestamps?.length) {
    const tsFormatted = summary.timestamps.map(ts => `[${ts.time}] ${ts.title} - ${ts.summary}`);
    addSection('Key Timestamps', tsFormatted, true);
  }
  addSection('Conclusion', summary.conclusion);

  // Footer page numbers
  const pageCount = doc.internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${pageCount} • TubeSage AI`, pageWidth / 2, pageHeight - 8, { align: 'center' });
  }

  const safeTitle = (summary.title || 'summary').replace(/[^a-z0-9]/gi, '_').toLowerCase().slice(0, 40);
  doc.save(`TubeSage_${safeTitle}.pdf`);
};
